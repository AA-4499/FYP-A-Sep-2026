-- =====================================================================
-- Supabase SQL: Training Model Outputs Table Definitions
-- Target: Store GRU model training/testing outputs for patient records (patient_detail)
-- =====================================================================

-- 1. Predictions Table: Stores point-by-point predictions vs actual CGM values in the held-out test period
CREATE TABLE IF NOT EXISTS public.training_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL DEFAULT 'initial_run',
    patient_id TEXT NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL,
    actual_glucose_mg_dl DOUBLE PRECISION NOT NULL,
    predicted_glucose_mg_dl DOUBLE PRECISION NOT NULL,
    persistence_baseline_mg_dl DOUBLE PRECISION,
    error_mg_dl DOUBLE PRECISION GENERATED ALWAYS AS (predicted_glucose_mg_dl - actual_glucose_mg_dl) STORED,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Indexes for efficient querying by patient and timestamp
CREATE INDEX IF NOT EXISTS idx_training_predictions_patient_time
    ON public.training_predictions (patient_id, timestamp);

CREATE INDEX IF NOT EXISTS idx_training_predictions_run_id
    ON public.training_predictions (run_id);

COMMENT ON TABLE public.training_predictions IS 'Rolling next 15-min CGM glucose predictions vs actual values per patient record';


-- 2. Metrics Table: Stores model evaluation metrics (overall and per-patient MAE / RMSE)
CREATE TABLE IF NOT EXISTS public.training_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL,
    patient_id TEXT NOT NULL DEFAULT 'ALL', -- 'ALL' for overall cohort metrics, or specific patient ID
    mae_mg_dl DOUBLE PRECISION NOT NULL,
    rmse_mg_dl DOUBLE PRECISION NOT NULL,
    baseline_mae_mg_dl DOUBLE PRECISION,
    baseline_rmse_mg_dl DOUBLE PRECISION,
    test_windows INTEGER,
    epochs INTEGER,
    batch_size INTEGER,
    hidden_dim INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_training_metrics_patient
    ON public.training_metrics (patient_id);

CREATE INDEX IF NOT EXISTS idx_training_metrics_run_id
    ON public.training_metrics (run_id);

COMMENT ON TABLE public.training_metrics IS 'Model test metrics including MAE and RMSE per training run';


-- 3. Timeline Splits Table: Stores timeline boundary metadata and sample counts per patient record
CREATE TABLE IF NOT EXISTS public.training_timeline_splits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL,
    patient_id TEXT NOT NULL,
    timeline_start TIMESTAMPTZ,
    timeline_end TIMESTAMPTZ,
    train_target_end_exclusive TIMESTAMPTZ,
    test_target_start TIMESTAMPTZ,
    observed_rows INTEGER,
    training_rows INTEGER,
    testing_rows INTEGER,
    test_windows INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_training_splits_patient
    ON public.training_timeline_splits (patient_id);

COMMENT ON TABLE public.training_timeline_splits IS 'Chronological 80/20 train/test timeline split metadata per patient record';


-- =====================================================================
-- Row Level Security (RLS) & Access Policies
-- =====================================================================
ALTER TABLE public.training_predictions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.training_metrics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.training_timeline_splits ENABLE ROW LEVEL SECURITY;

-- Allow public read access (e.g. for the React forecasting dashboard)
CREATE POLICY "Allow public read predictions"
    ON public.training_predictions FOR SELECT USING (true);

CREATE POLICY "Allow public read metrics"
    ON public.training_metrics FOR SELECT USING (true);

CREATE POLICY "Allow public read timeline splits"
    ON public.training_timeline_splits FOR SELECT USING (true);

-- Allow service role or authenticated users to insert / update / delete
CREATE POLICY "Allow service role insert predictions"
    ON public.training_predictions FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Allow service role insert metrics"
    ON public.training_metrics FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Allow service role insert timeline splits"
    ON public.training_timeline_splits FOR ALL USING (true) WITH CHECK (true);
